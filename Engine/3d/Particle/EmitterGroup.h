#pragma once

#include "3d/Camera/Camera.h"
#include "Math/WorldTransform.h"
#include "ParticleEmitter.h"

#include "list"

/// <summary>
/// 複数のパーティクルエミッターをまとめて管理し、更新・描画を行うクラスです。
/// </summary>
/// <remarks>
/// - グループ全体で使用するカメラ情報を管理し、各エミッターに適用します。  
/// - 初期化処理では、エミッター設定ファイルを読み込み、グループの座標・回転・スケールなどの初期状態を設定します。  
/// - 更新処理では、グループ全体の変換情報を反映した上で、個々のエミッターの状態を更新します。  
/// - 描画処理では、すべてのエミッターから描画コマンドを発行し、画面にパーティクルを表示します。  
/// - JSONファイルを読み込むことで、エミッターの設定やグループ構成を登録できます。  
/// - 現在のグループ構成や各エミッターの情報をJSON形式で保存することも可能です。  
/// - デフォルトエミッターの追加、すべてのエミッターのパーティクル発生・停止の制御ができます。  
/// </remarks>
class EmitterGroup {

	///-------------------------------------------/// 
	/// メンバ関数
	///-------------------------------------------///
public:

	/// <summary>
	/// パーティクルエミッターグループの初期化を行います。
	/// </summary>
	/// <remarks>
	/// - グループ全体で使用するカメラの参照を設定します。  
	/// - パーティクルエミッターの設定ファイルが格納されているディレクトリパスを設定します。  
	/// - 既存のエミッターリストをクリアし、新しい初期状態から生成を行えるようにします。  
	/// - グループのトランスフォームを初期化し、位置・回転・スケールなどの初期値を設定します。  
	/// </remarks>
	void Initialize(Camera* ptr);

	/// <summary>
	/// パーティクルエミッターグループの更新処理を行います。
	/// </summary>
	/// <remarks>
	/// - グループ全体のトランスフォームを更新し、位置・回転・スケールの変化を反映します。  
	/// - 各パーティクルエミッターに対して、グループのワールド変換を適用します。  
	/// - 各エミッターの状態を更新し、パーティクルの生成・移動・消滅などを行います。  
	/// </remarks>
	void Update();

	/// <summary>
	/// パーティクルエミッターグループの描画処理を行います。
	/// </summary>
	/// <remarks>
	/// - グループ内のすべてのパーティクルエミッターで描画コマンドを発行します。  
	/// </remarks>
	void Draw();

	/// <summary>
	/// ImGuiの表示
	/// </summary>
	void ImGui();

	/// <summary>
	/// 指定されたJSONファイルからパーティクルエミッター情報を読み込み、グループに登録します。
	/// </summary>
	/// <remarks>
	/// - ファイル名をもとにディレクトリパスを構築し、JSON形式のデータを読み込みます。  
	/// - ファイルが開けない場合はエラーメッセージを表示し、プログラムを停止します。  
	/// - 読み込んだJSONデータからグループ名を取得し、グループに設定します。  
	/// - JSON内に定義された各エミッター情報に基づき、エミッターインスタンスを生成・初期化します。  
	/// - エミッターにはあらかじめ設定されたテクスチャリストを登録し、カメラ情報を渡して初期化します。  
	/// - 初期化が完了したエミッターは、グループのリストに追加されます。  
	/// </remarks>
	void LoadEmitter(std::string fileName);

	/// <summary>
	/// 現在のパーティクルエミッターグループの情報をJSONファイルに保存します。
	/// </summary>
	/// <remarks>
	/// - グループ名と登録されているすべてのエミッター名をJSON形式で構築します。  
	/// - 保存先のディレクトリが存在しない場合は、自動でディレクトリを作成します。  
	/// - ファイル書き込みに失敗した場合はエラーメッセージを表示し、処理を中断します。  
	/// - JSONデータは見やすいようインデント付きでファイルに書き込みます。  
	/// - 各エミッターについて個別のパラメータもファイルにエクスポートして、詳細情報を保存します。  
	/// </remarks>
	void SaveEmitter();

	/// <summary>
	/// デフォルトのパーティクルエミッターをグループに追加します。
	/// </summary>
	/// <remarks>
	/// - すでに「default」という名前のエミッターが存在する場合は追加処理を行いません。  
	/// - 新しいエミッターを生成し、テクスチャリストを設定して初期化します。  
	/// - 初期化後、エミッターを管理リストに登録し、描画や更新処理の対象とします。  
	/// </remarks>
	void AddEmitter();

	/// <summary>
	/// グループ内のすべてのパーティクルエミッターからパーティクルを発生させます。
	/// </summary>
	/// <remarks>
	/// - 管理リストに登録されているすべてのエミッターに対して、個別にパーティクルの発生処理を呼び出します。  
	/// - 各エミッターの発生条件やタイミングに基づき、パーティクルが生成されて更新対象として描画されます。  
	/// </remarks>
	void Emit();

	/// <summary>
	/// グループ内のすべてのパーティクルエミッターの発生を停止します。
	/// </summary>
	/// <remarks>
	/// - 管理リストに登録されているすべてのエミッターに対して、発生フラグをfalseに設定します。  
	/// - この処理を行うことで、エミッターは新たなパーティクルを生成しなくなりますが、
	///   すでに生成済みのパーティクルは引き続き更新・描画されます。  
	/// </remarks>
	void Stop();

	///-------------------------------------------/// 
	/// ゲッター・セッター
	///-------------------------------------------///
public:

	/// <summary>
	/// エミッターリストを取得
	/// </summary>
	/// <returns>エミッターリスト</returns>
	std::list<ParticleEmitter*> GetEmitterList();

	/// <summary>
	/// グループ名を取得
	/// </summary>
	/// <returns>グループ名</returns>
	std::string GetName() { return name_; }

	/// <summary>
	/// トランスフォームを取得
	/// </summary>
	/// <returns>トランスフォーム</returns>
	WorldTransform& GetWorldTransform() { return transform_; }

	/// <summary>
	/// テクスチャリストの設定
	/// </summary>
	/// <param name="list">テクスチャリスト</param>
	void SetTextureList(std::vector<std::string> list) { textureList_ = list; }

	/// <summary>
	/// トランスフォームの設定
	/// </summary>
	/// <param name="worldTransform">トランスフォーム</param>
	void SetWorldTransform(WorldTransform worldTransform) { transform_ = worldTransform; }

	///-------------------------------------------/// 
	/// メンバ変数
	///-------------------------------------------///
private:

	//カメラ
	Camera* camera_;

	//エミッターのリスト
	std::list<std::unique_ptr<ParticleEmitter>> particleEmitters_;

	//テクスチャリスト
	std::vector<std::string> textureList_;

	//ワールドトランスフォーム
	WorldTransform transform_;

	//グループ名
	std::string name_;

	//ディレクトリパス
	std::string directoryPath_;
};