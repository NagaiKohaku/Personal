#pragma once

#include "Base/LayerType.h"

#include "functional"
#include "map"
#include "vector"

/// <summary>
/// 描画処理を統括し、登録された描画コマンドをレイヤー順に実行するクラスです。
/// </summary>
/// <remarks>
/// - シングルトンパターンで実装され、アプリケーション全体で 1 つのインスタンスを共有します。  
/// - 描画キューに登録された描画処理を順序に従って実行し、スワップチェーンやオフスクリーンに描画します。  
/// - 通常描画とオフスクリーン描画を分けて管理でき、レイヤーごとの描画順序を制御可能です。  
/// - デバッグレイヤーの場合は、デバッグ表示が有効なときのみ描画コマンドを実行します。  
/// - 描画後は各描画キューをクリアし、次フレーム用に初期化します。  
/// - AddDraw() により、描画処理を通常描画またはオフスクリーン描画のいずれかに追加できます。  
/// </remarks>
class Renderer {

	///-------------------------------------------/// 
	/// メンバ関数
	///-------------------------------------------///
public:

	/// <summary>
	/// Rendererのシングルトンインスタンスを取得します。
	/// </summary>
	/// <remarks>
	/// 返り値に静的インスタンスを返します。
	/// </remarks>
	static Renderer* GetInstance();

	/// <summary>
	/// レンダラーを初期化します。
	/// </summary>
	/// <remarks>
	/// - 描画キューをクリアして初期状態にします。
	/// </remarks>
	void Initialize();

	/// <summary>
	/// 登録された描画コマンドをレイヤー順に実行し、スワップチェーンに描画します。
	/// </summary>
	/// <remarks>
	/// - 下位レイヤーから順に描画キューを処理します。  
	/// - デバッグレイヤーの場合、デバッグ表示が有効な場合のみ描画コマンドを実行します。  
	/// - 通常レイヤーはすべての描画コマンドを実行します。  
	/// - 描画後、描画キューをクリアして初期状態に戻します。  
	/// </remarks>
	void SwapChainDraw();

	/// <summary>
	/// 登録されたオフスクリーン描画コマンドをレイヤー順に実行します。
	/// </summary>
	/// <remarks>
	/// - 下位レイヤーから順にオフスクリーン描画キューを処理します。  
	/// - デバッグレイヤーの場合、デバッグ表示が有効な場合のみ描画コマンドを実行します。  
	/// - 通常レイヤーはすべての描画コマンドを実行します。  
	/// - 描画後、オフスクリーン描画キューをクリアして初期化します。  
	/// </remarks>
	void OffScreenDraw();

	/// <summary>
	/// 描画コマンドを指定したレイヤーと描画先に追加します。
	/// </summary>
	/// <remarks>
	/// - isOffScreenがtrueの場合、オフスクリーン描画キューに追加します。  
	/// - isOffScreenがfalseの場合、通常描画キューに追加します。  
	/// - funcに指定した描画処理が登録され、後で描画時に実行されます。  
	/// </remarks>
	void AddDraw(LayerType layer, bool isOffScreen,std::function<void()> func);

	///-------------------------------------------/// 
	/// クラス内関数
	///-------------------------------------------///
private:

	/// <summary>
	/// 通常描画キューに登録されている全ての描画コマンドをクリアします。
	/// </summary>
	/// <remarks>
	/// - レイヤーごとに保持している描画コマンドをすべて削除します。  
	/// - 描画キューを初期状態に戻すことで、次フレームの描画準備を行います。  
	/// </remarks>
	void ClearQueue();

	/// <summary>
	/// オフスクリーン描画キューに登録されている全ての描画コマンドをクリアします。
	/// </summary>
	/// <remarks>
	/// - レイヤーごとに保持しているオフスクリーン描画コマンドをすべて削除します。  
	/// - 描画キューを初期状態に戻すことで、次フレームのオフスクリーン描画準備を行います。  
	/// </remarks>
	void ClearOffScreenQueue();

	/// <summary>
	/// 現在のビルドがデバッグモードかどうかを判定します。
	/// </summary>
	/// <returns>
	/// デバッグビルドの場合はtrue、リリースビルドの場合はfalseを返します。
	/// Defineだと改行がおかしくなるため関数として実装しました。
	/// </returns>
	bool isDebug();

	///-------------------------------------------/// 
	/// メンバ変数
	///-------------------------------------------///
private:

	//描画コマンドキュー
	std::map<LayerType, std::vector<std::function<void()>>> drawQueue_;

	//OffScreen用の描画コマンドキュー
	std::map<LayerType, std::vector<std::function<void()>>> offScreenDrawQueue_;
};