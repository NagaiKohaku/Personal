#pragma once

#include "Bullet/BulletBase.h"

#include "3d/Collider/SphereCollider.h"

#include "memory"

/// <summary>
/// 敵弾を管理するクラスです。
/// </summary>
/// <remarks>
/// - 敵弾の生成から移動、衝突判定、描画までの一連の処理を管理します。  
/// - フレームごとの更新や寿命管理を行い、必要に応じて消滅処理を実行します。  
/// - 当たり判定用の球体コライダーを保持し、プレイヤーとの衝突判定を行います。  
/// - 描画用オブジェクトとコライダーの状態を常に最新の状態へ同期します。  
/// </remarks>
class EnemyBullet : public BulletBase {

	///-------------------------------------------/// 
	/// メンバ関数
	///-------------------------------------------///
public:

	/// <summary>
	/// 弾が破棄される際に関連するコライダーを削除します。
	/// </summary>
	/// <remarks>
	/// - 弾が存在しなくなるタイミングで、衝突判定に使用していた要素を登録先から取り除きます。  
	/// - これにより不要な衝突判定が残らないようにします。
	/// </remarks>
	~EnemyBullet();

	/// <summary>
	/// 弾を初期化し、パラメータを設定します。
	/// </summary>
	/// <param name="pos">生成時の座標を指定します。</param>
	/// <param name="direction">移動方向を指定します。</param>
	/// <remarks>
	/// - 大きさや移動速度などのパラメータを設定します。
	/// - 描画用オブジェクトを生成し、座標やサイズをパラメータで設定します。  
	/// - 衝突判定用の球体コライダーを生成し、敵弾としての識別タグを設定します。  
	/// </remarks>
	void Initialize(Vector3 pos, Vector3 direction) override;

	/// <summary>
	/// 弾の状態を更新します
	/// </summary>
	/// <remarks>
	/// - 経過時間を用いて寿命を進め、上限に達した場合は消滅状態にします。  
	/// - 弾を前進させる処理を行います。  
	/// - 接触していた場合の処理を行います。  
	/// - 表示用オブジェクトの情報を最新化します。  
	/// - 当たり判定用コライダーの位置や状態を更新します。  
	/// </remarks>
	void Update() override;

	/// <summary>
	/// 弾の座標更新処理を行います
	/// </summary>
	/// <remarks>
	/// - 表示用オブジェクトの位置情報のみを最新の状態に反映します。  
	/// </remarks>
	void TransformUpdate() override;

	/// <summary>
	/// 弾の描画処理を行います
	/// </summary>
	/// <remarks>
	/// - 表示用オブジェクトを描画します。  
	/// - 当たり判定用コライダーの描画を行います。  
	/// </remarks>
	void Draw() override;

	///-------------------------------------------/// 
	/// クラス内処理関数
	///-------------------------------------------///
private:

	/// <summary>
	/// 弾の移動処理を行います
	/// </summary>
	/// <remarks>
	/// - 現在の座標に移動量を加算し、次のフレームの位置を決定します。  
	/// </remarks>
	void Move();

	/// <summary>
	/// 他オブジェクトと接触している場合の処理を行います
	/// </summary>
	/// <remarks>
	/// - 当たり判定用コライダーが接触した瞬間であるかを確認します。  
	/// - 接触している相手がプレイヤーである場合、弾を消滅状態にします。  
	/// </remarks>
	void IsCollision();

	///-------------------------------------------/// 
	/// メンバ変数
	///-------------------------------------------///
private:

	//コライダー
	std::unique_ptr<SphereCollider> collider_;

};