#pragma once

#include "memory"

class Object3D;

/// <summary>
/// 3D空間内の地面オブジェクトを管理するクラスです。
/// </summary>
/// <remarks>
/// - 内部に3Dオブジェクトを保持し、初期化・更新・描画処理を行います。
/// - UV座標のスクロールを用いたテクスチャアニメーションを実装しています。
/// </remarks>
class Ground {

	///-------------------------------------------/// 
	/// メンバ関数
	///-------------------------------------------///
public:

	/// <summary>
	/// 地面オブジェクトを初期化します。
	/// </summary>
	/// <remarks>
	/// - 3Dオブジェクトを生成し、初期化します。
	/// - 平面モデルを設定し、テクスチャを読み込み適用します。
	/// - オブジェクトのスケールと回転を設定します。
	/// - 環境光係数を初期化します。
	/// - UV座標Yを初期値に設定します。
	/// </remarks>
	void Initialize();

	/// <summary>
	/// 地面オブジェクトの更新処理を行います。
	/// </summary>
	/// <remarks>
	/// - 内部の3Dオブジェクトの更新処理を呼び出します。
	/// - UV座標Yを時間経過に応じて更新します。
	/// - UV変換行列（移動、回転、スケール）を計算し、モデルに設定します。
	/// - これによりテクスチャのスクロール表現を実現します。
	/// </remarks>
	void Update();

	/// <summary>
	/// 地面オブジェクトの座標更新を行います。
	/// </summary>
	/// <remarks>
	/// - 内部の3Dオブジェクトの更新処理を呼び出し、ワールド変換を反映させます。
	/// - UVスクロールやその他の更新処理は行いません。
	/// </remarks>
	void TransformUpdate();

	/// <summary>
	/// 地面オブジェクトを描画します。
	/// </summary>
	/// <remarks>
	/// - 内部の3Dオブジェクトをオブジェクトレイヤーに描画します。
	/// </remarks>
	void Draw();

	///-------------------------------------------/// 
	/// メンバ変数
	///-------------------------------------------///
private:

	//地面オブジェクト
	std::unique_ptr<Object3D> object_;

	//UV座標Y
	float uvPosY;
};