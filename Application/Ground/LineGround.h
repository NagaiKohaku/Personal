#pragma once

#include "3d/Object/DebugLine.h"

#include "memory"
#include "list"

/// <summary>
/// ライン状の床オブジェクトを管理するクラスです。
/// </summary>
/// <remarks>
/// - 床を構成する縦ラインと横ラインを保持し、初期化・更新・描画を行います。
/// - 横ラインはスクロール移動し、範囲外に出た場合はループさせます。
/// - 縦ラインは固定表示され、中央ラインのみ赤色で強調されます。
/// - デバッグ用のライン表現や床の動きの視覚化に使用されます。
/// </remarks>
class LineGround {

	///-------------------------------------------/// 
	/// メンバ関数
	///-------------------------------------------///
public:

	/// <summary>
	/// ライン状の床オブジェクトを初期化します。
	/// </summary>
	/// <remarks>
	/// - 床を構成する縦および横のラインを生成します。
	/// - ラインの分割数、間隔、移動速度などのパラメータを設定します。
	/// - 縦ラインの中央は赤色で表示し、それ以外は白色で表示します。
	/// - 各ラインはDebugLineオブジェクトとして生成・初期化され、内部コンテナに保持されます。
	/// </remarks>
	void Initialize();

	/// <summary>
	/// ライン状の床オブジェクトの更新処理を行います。
	/// </summary>
	/// <remarks>
	/// - 床全体の移動処理を行います。
	/// - 縦ラインおよび横ラインの各DebugLineオブジェクトの更新処理を呼び出します。
	/// - ラインの位置や状態が毎フレーム反映されます。
	/// </remarks>
	void Update();

	/// <summary>
	/// ライン状の床オブジェクトを描画します。
	/// </summary>
	/// <remarks>
	/// - 縦ラインおよび横ラインの各DebugLineオブジェクトをオブジェクトレイヤーに描画します。
	/// - ラインの色や位置に応じて描画が反映されます。
	/// </remarks>
	void Draw();

	///-------------------------------------------/// 
	/// クラス内処理関数
	///-------------------------------------------///
private:

	/// <summary>
	/// ライン状の床オブジェクトの横ラインを移動させます。
	/// </summary>
	/// <remarks>
	/// - 横ラインのZ座標を速度に応じて減少させます。
	/// - ラインが表示範囲外に出た場合は、Z座標をリセットしてループさせます。
	/// - 縦ラインは移動させず、横ラインのみスクロールさせます。
	/// </remarks>
	void Move();

	///-------------------------------------------/// 
	/// メンバ変数
	///-------------------------------------------///
private:

	//縦ライン群
	std::list<std::unique_ptr<DebugLine>> verticalLines_;

	//横ライン群
	std::list<std::unique_ptr<DebugLine>> horizontalLines_;

	//ライン分割数
	float lineDivide_ = 30.0f;

	//ライン間隔
	float lineDistance_ = 5.0f;

	//移動速度
	float speed_;
};