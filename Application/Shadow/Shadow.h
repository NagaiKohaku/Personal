#pragma once

#include "memory"

#include "3d/Object/Object3D.h"

#include "Math/Vector3.h"

/// <summary>
/// キャラクターや物体の位置に応じて影を生成・管理するクラス
/// </summary>
/// <remarks>
/// - 3Dオブジェクトを利用して影を表現する
/// - 高さに応じて影のサイズを変化させる
/// - 地面に潜った場合は描画を無効化する
/// - 初期化・更新・描画の3つの操作を提供する
/// </remarks>
class Shadow {

	///-------------------------------------------/// 
	/// メンバ関数
	///-------------------------------------------///
public:

	/// <summary>
	/// 影用オブジェクトを生成し初期設定を行う
	/// </summary>
	/// <remarks>
	/// - 影として利用する3Dオブジェクトを生成する
	/// - モデルを球形に設定し扁平な形状へ変更する
	/// - 影色を黒に設定し環境反射を無効化する
	/// - 影用パラメータの最大長と最大拡大率を設定する
	/// - 描画を行うかどうかの初期状態を有効にする
	/// </remarks>
	void Initialize();

	/// <summary>
	/// 指定座標に応じて影の位置とサイズを更新する
	/// </summary>
	/// <param name="pos">影の基準となる座標</param>
	/// <remarks>
	/// - 引数座標を影オブジェクトの位置に反映する
	/// - 高さに応じて影の拡大率を計算する
	/// - 拡大率が極端に小さくならないよう制限する
	/// - 計算したサイズを影オブジェクトに適用する
	/// - 影オブジェクトを毎フレーム更新する
	/// - 座標が地面以下なら描画フラグを無効にする
	/// </remarks>
	void Update(Vector3 pos);

	/// <summary>
	/// 影オブジェクトを描画する
	/// </summary>
	/// <remarks>
	/// - 描画フラグが有効な場合のみ影を描画する
	/// - 影オブジェクトを指定レイヤーで描画する
	/// </remarks>
	void Draw();

	///-------------------------------------------/// 
	/// メンバ変数
	///-------------------------------------------///
private:

	// 影オブジェクト
	std::unique_ptr<Object3D> shadow_;

	// オブジェクト間の距離
	float maxLength_;

	// 最大サイズ
	float maxScale_;

	// 描画フラグ
	bool isDraw_;

};