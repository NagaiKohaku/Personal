#pragma once

#include <2d/Object/Object2D.h>
#include <Math/WorldTransform.h>

#include <3d/Camera/Camera.h>
#include <Player/Player.h>

#include <memory>
#include <vector>

/// <summary>
/// フェード演出を管理するクラスです。
/// </summary>
/// <remarks>
/// - フェードインおよびフェードアウトの処理を統括し、画面全体に対する視覚効果を提供します。  
/// - リング形状や円形のスプライトを用いたアニメーション表現を行います。  
/// - プレイヤーの位置を2D座標に変換し、スプライトの中心位置に同期させることが可能です。  
/// - 状態管理により、フェードイン、フェードイン完了、フェードアウト、フェードアウト完了の各フェーズを制御します。  
/// - 内部でスプライトのサイズや表示時間を管理し、イージング計算による滑らかな変化を実現します。  
/// - カメラおよびプレイヤーの参照を保持し、視点や対象の位置に応じたフェード演出が可能です。  
/// - シングルトンとして提供され、アプリケーション全体で一つのインスタンスを使用して管理されます。  
/// </remarks>
class Fade {

	///-------------------------------------------/// 
	/// 構造体
	///-------------------------------------------///
public:

	//フェードの状態
	enum FadeState {
		NONE,
		FADE_IN,
		FADE_IN_END,
		FADE_OUT,
		FADE_OUT_END
	};

	//フェード用にスプライトの情報をまとめた構造体
	struct FadeSprite {
		std::unique_ptr<Object2D> sprite;
		Vector2 startSize;
		Vector2 endSize;
		float startTime;
		float endTime;
	};

	///-------------------------------------------/// 
	/// メンバ関数
	///-------------------------------------------///
public:

	/// <summary>
	/// Fadeのシングルトンインスタンスを取得します。
	/// </summary>
	/// <remarks>
	/// 返り値に静的インスタンスを返します。
	/// </remarks>
	static Fade* GetInstance();

	/// <summary>
	/// フェード処理に必要なスプライトやリソースを初期化する関数です。
	/// </summary>
	/// <remarks>
	/// - 使用するテクスチャをスプライト管理クラスを通じてロードします。  
	/// - フェード演出に使用するリング状のスプライトを複数生成します。  
	/// - 中心部分の円形スプライトも生成し、フェード時の表現に利用します。  
	/// </remarks>
	void Initialize();

	/// <summary>
	/// フェード処理の状態を毎フレーム更新する関数です。
	/// </summary>
	/// <remarks>
	/// - フェードインおよびフェードアウトの進行を管理し、各タイマーや状態を更新します。  
	/// - カメラとプレイヤーが設定されている場合、プレイヤーの3D座標を画面上の2D座標に変換し、フェード演出に反映します。  
	/// - プレイヤーの座標が正しく変換できた場合のみ2D座標を更新します。  
	/// - 管理している全てのフェード用スプライトに対して、個別の更新処理を呼び出し描画準備を整えます。  
	/// </remarks>
	void Update();

	/// <summary>
	/// 管理しているフェード用スプライトを画面に描画する関数です。
	/// </summary>
	/// <remarks>
	/// - 全てのフェード用スプライトに対して、描画レイヤーを指定して描画処理を呼び出します。  
	/// </remarks>
	void Draw();

	/// <summary>
	/// フェードイン処理を開始する関数です。
	/// </summary>
	/// <remarks>
	/// - フェードの状態をフェードインに切り替え、処理を開始します。  
	/// - 内部タイマーをリセットして、フレーム単位で進行できるようにします。  
	/// - 管理している全てのスプライトの座標を画面中央に設定し、サイズを開始サイズに初期化します。  
	/// </remarks>
	void StartFadeIn();

	/// <summary>
	/// フェードインの進行処理を行います。
	/// </summary>
	/// <remarks>
	/// - フェードがフェードイン状態のときのみ処理が行われます。  
	/// - 内部タイマーをフレーム単位で減少させ、スプライトの開始・終了時間に応じて更新します。  
	/// - スプライトごとに経過時間の割合を算出し、イージング関数を用いてサイズを補間します。  
	/// - スプライトの位置はプレイヤーの2D座標に同期されます。  
	/// - 全てのスプライトのフェードインが完了すると、状態をフェードイン終了に切り替えます。  
	/// </remarks>
	void FadeInUpdate();

	/// <summary>
	/// フェードアウト処理を開始する関数です。
	/// </summary>
	/// <remarks>
	/// - フェードの状態をフェードアウトに切り替え、処理を開始します。  
	/// - 内部タイマーをリセットして、フレーム単位で進行できるようにします。  
	/// - 管理している全てのスプライトの座標を画面中央に設定し、サイズを開始サイズに初期化します。  
	/// </remarks>
	void StartFadeOut();

	/// <summary>
	/// フェードアウトの進行処理を行います。
	/// </summary>
	/// <remarks>
	/// - フェードがフェードアウト状態のときのみ処理が行われます。  
	/// - 内部タイマーをフレーム単位で増加させ、スプライトの開始・終了時間に応じて更新します。  
	/// - スプライトごとに経過時間の割合を算出し、イージング関数を用いてサイズを補間します。  
	/// - スプライトの位置はプレイヤーの2D座標に同期されます。  
	/// - 全てのスプライトのフェードアウトが完了すると、状態をフェードアウト終了に切り替えます。  
	/// </remarks>
	void FadeOutUpdate();

	///=====================================================/// 
	/// ゲッター・セッター
	///=====================================================///
public:

	/// <summary>
	/// フェード状態の取得
	/// </summary>
	FadeState GetState() const { return state_; }

	/// <summary>
	/// カメラの取得
	/// </summary>
	Camera* GetCamera() { return camera_; }

	/// <summary>
	/// プレイヤーの取得
	/// </summary>
	Player* GetPlayer() { return player_; }

	/// <summary>
	/// フェード状態の設定
	/// </summary>
	void SetState(FadeState state) { state_ = state; }

	/// <summary>
	/// カメラの設定
	/// </summary>
	void SetCamera(Camera* ptr) { camera_ = ptr; }

	/// <summary>
	/// プレイヤーの設定
	/// </summary>
	void SetPlayer(Player* ptr) { player_ = ptr; }

	///=====================================================/// 
	/// クラス内関数
	///=====================================================///
private:

	/// <summary>
	/// リング形状のスプライトを生成し、フェード用の管理リストに追加します。
	/// </summary>
	/// <remarks>
	/// - 新しい2Dオブジェクトを生成し、初期化処理を行います。  
	/// - リング用の画像を設定し、パラメータを設定します。  
	/// - 管理リストに追加する際、最初のスプライトであればタイマーを0から開始し、  
	///   それ以降は前のスプライトの終了時間を基準に開始時間を調整します。  
	/// - 各スプライトに開始サイズ、終了サイズ、開始時間、終了時間を設定します。  
	/// </remarks>
	void CreateRingSprite();

	/// <summary>
	/// 円形のスプライトを生成し、フェード用の管理リストに追加します。
	/// </summary>
	/// <remarks>
	/// - 新しい2Dオブジェクトを生成して初期化します。  
	/// - 円形用の画像を設定し、パラメータを設定します。  
	/// - 初期サイズと画面中央の位置を設定します。  
	/// - 管理リストへの追加時、開始時間は前のスプライトの終了時間を基準に少し前倒しに設定します。  
	/// - 各スプライトに開始サイズ、終了サイズ、開始時間、終了時間を設定し、リストに追加します。  
	/// </remarks>
	void CreateCircleSprite();

	///=====================================================/// 
	/// メンバ変数
	///=====================================================///
private:

	//フェード状態
	FadeState state_ = FadeState::NONE;

	//フェードスプライト
	std::vector<FadeSprite> fadeSprites_;

	//カメラ
	Camera* camera_;

	//プレイヤー
	Player* player_;

	//プレイヤーの2D座標
	Vector2 playerPos2D_;

	//アルファ値
	float alpha_ = 0.0f;

	//タイマー
	float timer_ = 0.0f;

	//最大タイマー
	float maxTimer_ = 1.0f;

	//フェード速度
	float fadeSpeed_ = 0.02f;
};